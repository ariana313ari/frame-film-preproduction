"""Markdown production-package export."""
from __future__ import annotations

import re
from datetime import datetime

from schemas import ArtifactStatus, Project, Severity, Stage, ValidationIssue

# key -> (English, Mongolian)
_HEADINGS = {
    "summary": ("Project Summary", "Төслийн товч мэдээлэл"),
    "logline": ("Logline", "Логлайн"),
    "synopsis": ("Synopsis", "Синопсис"),
    "characters": ("Characters", "Дүрүүд"),
    "script": ("Script", "Сценар"),
    "scenes": ("Scene Breakdown", "Дүр зургийн задлал"),
    "shots": ("Shot List", "Зураглалын жагсаалт (Shot List)"),
    "resources": ("Production Resources", "Үйлдвэрлэлийн нөөц"),
    "schedule": ("Schedule & Assumptions", "Хуваарь ба таамаглал"),
    "validation": ("Validation Notes", "Шалгалтын тэмдэглэл"),
}

_NOT_AVAILABLE = ("_Not generated yet._", "_Одоогоор үүсгээгүй байна._")


def _h(key: str, lang: str) -> str:
    en, mn = _HEADINGS[key]
    return en if lang == "en" else mn


def _na(lang: str) -> str:
    return _NOT_AVAILABLE[0] if lang == "en" else _NOT_AVAILABLE[1]


def _cell(value) -> str:
    return re.sub(r"\s+", " ", str(value)).replace("|", "\\|").strip() or "—"


def _table(headers: list[str], rows: list[list]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(_cell(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def _origin_label(project: Project, stage: Stage) -> str:
    origin = project.provenance.get(stage, "")
    if origin == "sample":
        return "SAMPLE DATA (static example, not generated by a model)"
    if origin.startswith("model"):
        return origin.replace("model:", "AI-generated · ")
    return origin or ""


def _issue_lines(issues: list[ValidationIssue], source: str) -> list[str]:
    icons = {Severity.ERROR: "🔴 ERROR", Severity.WARNING: "🟠 WARNING", Severity.INFO: "🔵 INFO"}
    lines = []
    for issue in issues:
        if issue.source != source:
            continue
        where = []
        if issue.scene_number:
            where.append(f"scene {issue.scene_number}")
        if issue.shot_number:
            where.append(f"shot {issue.shot_number}")
        suffix = f" _({', '.join(where)})_" if where else ""
        fix = f"\n  - Suggested fix: {issue.suggestion}" if issue.suggestion else ""
        lines.append(f"- **{icons[issue.severity]}** `{issue.code}` {issue.message}{suffix}{fix}")
    return lines


def project_to_markdown(project: Project, issues: list[ValidationIssue] | None = None,
                        checked: bool | None = None) -> str:
    """Render the whole project as a Markdown document.

    `issues` overrides `project.issues` (export_package passes freshly computed
    deterministic findings when no validation has been run). `checked` says whether
    those issues come from an actual validation run, so "no findings" can be told
    apart from "never validated".
    """
    lang = project.language
    issues = project.issues if issues is None else issues
    checked = project.is_fresh(Stage.VALIDATION) if checked is None else checked
    out: list[str] = [f"# {project.name} — Production Package", ""]
    out.append(f"_Generated by FRAME on {datetime.now():%Y-%m-%d %H:%M}._")

    stale = [s.value for s in Stage if project.get_status(s) == ArtifactStatus.OUTDATED]
    if stale:
        out += ["", f"> ⚠️ **Outdated sections:** {', '.join(stale)}. They were created before an upstream "
                    "change and may no longer match the script. Regenerate them before production."]
    sample_stages = [s.value for s in Stage if project.provenance.get(s) == "sample"]
    if sample_stages:
        out += ["", f"> ℹ️ Sample data is included for: {', '.join(sample_stages)} "
                    "(a static demo example, not model output)."]

    # 1 Summary
    out += ["", f"## 1. {_h('summary', lang)}", ""]
    out.append(_table(["Field", "Value"], [
        ["Genre", project.genre],
        ["Target duration", f"{project.duration_minutes:g} min"],
        ["Max locations", project.max_locations or "not limited"],
        ["Max actors", project.max_actors or "not limited"],
        ["Budget level", project.budget.value.lower()],
        ["Visual style", project.visual_style],
        ["Constraints", project.constraints],
        ["Available equipment", ", ".join(project.equipment)],
        ["Premise", project.idea],
    ]))
    origins = [(st.value, _origin_label(project, st)) for st in Stage if project.provenance.get(st)]
    if origins:
        out += ["", "**Where each section comes from:** " + "; ".join(f"{name} — {label}" for name, label in origins)]
    if project.approved_decisions:
        out += ["", "**Approved creative decisions:**"] + [f"- {d}" for d in project.approved_decisions]

    # 2-4 Story
    out += ["", f"## 2. {_h('logline', lang)}", "", project.logline or _na(lang)]
    out += ["", f"## 3. {_h('synopsis', lang)}", "", project.synopsis or _na(lang)]
    out += ["", f"## 4. {_h('characters', lang)}", ""]
    if project.characters:
        for c in project.characters:
            line = f"- **{c.name}**" + (f" ({c.role})" if c.role else "")
            if c.description:
                line += f" — {c.description}"
            if c.details:
                line += f" _Continuity details: {', '.join(c.details)}_"
            out.append(line)
    else:
        out.append(_na(lang))

    # 5 Script
    out += ["", f"## 5. {_h('script', lang)}", ""]
    if project.script_scenes:
        for s in project.script_scenes:
            out += [f"### Scene {s.number}" + (f" — {s.heading}" if s.heading else ""), "", s.text, ""]
    else:
        out.append(_na(lang))

    # 6 Scenes
    out += ["", f"## 6. {_h('scenes', lang)}", ""]
    if project.scenes:
        out.append(_table(
            ["#", "Location", "Time", "Characters", "Props", "Action", "Est. sec"],
            [[s.number, s.location, s.time_of_day.value, ", ".join(s.characters), ", ".join(s.props),
              s.action, f"{s.estimated_duration_sec:g}"] for s in project.scenes]))
        out.append(f"\nTotal estimated: **{project.total_scene_seconds:g} s** "
                   f"(target {project.duration_seconds:g} s).")
    else:
        out.append(_na(lang))

    # 7 Shots
    out += ["", f"## 7. {_h('shots', lang)}", ""]
    if project.shots:
        out.append(_table(
            ["#", "Scene", "Type", "Angle", "Movement", "Description", "Audio", "Est. sec"],
            [[s.number, s.scene_number, s.shot_type.value, s.camera_angle.value, s.movement.value,
              s.description, s.audio_notes, f"{s.estimated_duration_sec:g}"] for s in project.shots]))
    else:
        out.append(_na(lang))

    # 8 Resources
    out += ["", f"## 8. {_h('resources', lang)}", ""]
    plan = project.plan
    if plan:
        out.append("**Props**")
        out += [f"- {p.name} (scenes {', '.join(map(str, p.scene_numbers))})" for p in plan.props] or ["- —"]
        out += ["", "**Equipment**"]
        for e in plan.equipment:
            avail = {True: " ✅ listed as available", False: " ❓ not in your equipment list", None: ""}[e.available]
            out.append(f"- {e.name} — {e.reason}{avail}")
        out += ["", "**Locations**"]
        out += [f"- {l.name} (scenes {', '.join(map(str, l.scene_numbers))}; {l.time_of_day})"
                for l in plan.locations] or ["- —"]
    else:
        out.append(_na(lang))

    # 9 Schedule
    out += ["", f"## 9. {_h('schedule', lang)}", ""]
    if plan and plan.schedule:
        out.append(_table(["Day", "Order", "Block", "Scenes", "Est. min", "Notes"],
                          [[b.day, b.order, b.label, ", ".join(map(str, b.scene_numbers)),
                            b.estimated_minutes, b.notes] for b in plan.schedule]))
        out.append(f"\nEstimated total: **~{plan.total_minutes} min** over **{plan.shoot_days} day(s)**. "
                   "These are planning estimates, not guaranteed durations.")
        out += ["", "**Assumptions**"] + [f"- {a}" for a in plan.assumptions]
    else:
        out.append(_na(lang))

    # 10 Validation
    out += ["", f"## 10. {_h('validation', lang)}", ""]
    if issues or checked:
        det = _issue_lines(issues, "deterministic")
        mod = _issue_lines(issues, "model")
        out.append("**Rule-based checks (deterministic):**")
        out += det or ["- No findings."]
        out += ["", "**AI-generated suggestions (not guaranteed, please verify manually):**"]
        out += mod or ["- None (AI review not run or reported nothing)."]
    else:
        out.append("_Validation has not been run for this project._")
    out += ["", "---", "_Semantic continuity checks are assisted by an AI model and are not exhaustive._", ""]
    return "\n".join(out)


def safe_filename(name: str, suffix: str) -> str:
    stem = re.sub(r"[^\w\-]+", "_", name, flags=re.UNICODE).strip("_") or "frame_project"
    return f"{stem}{suffix}"
